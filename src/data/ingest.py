"""
IMS Bearing Data Ingestion to PostgreSQL
Bulk-inserts features into Postgres using efficient COPY protocol.
"""
import pandas as pd
import numpy as np
from pathlib import Path
from typing import List, Optional
import logging
from sqlalchemy import create_engine, text
from sqlalchemy.engine import Engine
import os
from tqdm import tqdm

logger = logging.getLogger(__name__)


class IMSIngestor:
    """Production-grade bulk ingestor for IMS features"""

    def __init__(self, db_url: Optional[str] = None):
        """
        Initialize database connection.
        db_url format: postgresql://user:password@localhost:5432/anudeep
        """
        if db_url is None:
            db_url = os.getenv(
                'DATABASE_URL',
                'postgresql://postgres:postgres@localhost:5432/anudeep'
            )

        self.engine = create_engine(db_url, echo=False)
        logger.info(f"Connected to database: {self.engine.url.database}")

    def test_connection(self) -> bool:
        """Test database connectivity"""
        try:
            with self.engine.connect() as conn:
                result = conn.execute(text("SELECT 1")).scalar()
                logger.info("Database connection OK")
                return result == 1
        except Exception as e:
            logger.error(f"Connection failed: {e}")
            return False

    def bulk_insert_features(
            self,
            df: pd.DataFrame,
            table_name: str = 'features',
            chunksize: int = 5000
    ) -> int:
        """
        Bulk-insert features using pandas.to_sql with fast method.

        Args:
            df: DataFrame matching features table schema
            table_name: Target table name
            chunksize: Rows per batch (tune for memory)

        Returns:
            Number of rows inserted
        """
        try:
            # Validate required columns
            required = ['file_name', 'timestamp', 'bearing_id', 'axis']
            missing = [c for c in required if c not in df.columns]
            if missing:
                raise ValueError(f"Missing columns: {missing}")

            # Ensure timestamp is datetime
            if not pd.api.types.is_datetime64_any_dtype(df['timestamp']):
                df['timestamp'] = pd.to_datetime(df['timestamp'])

            # Rename columns to match DB schema (lowercase, no special chars)
            df = df.rename(columns={
                'file': 'file_name',
                'channel': 'channel',
                'bearing': 'bearing_id'
            })

            # Drop feature_id if exists (auto-generated by DB)
            if 'feature_id' in df.columns:
                df = df.drop(columns=['feature_id'])

            n_rows = len(df)
            logger.info(f"Starting bulk insert: {n_rows} rows → {table_name}")

            # Use to_sql with method='multi' for batch inserts
            df.to_sql(
                name=table_name,
                con=self.engine,
                if_exists='append',
                index=False,
                chunksize=chunksize,
                method='multi'
            )

            logger.info(f"Successfully inserted {n_rows} rows")
            return n_rows

        except Exception as e:
            logger.error(f"Bulk insert failed: {e}")
            raise

    def ingest_from_parquet(
            self,
            parquet_path: Path,
            table_name: str = 'features'
    ) -> int:
        """
        Load features from parquet and ingest to Postgres.
        Handles your current set1_features_temporal.parquet format.
        """
        logger.info(f"Loading parquet: {parquet_path}")
        df = pd.read_parquet(parquet_path)

        # Map your column names to DB schema
        column_mapping = {
            'file': 'file_name',
            'bearing': 'bearing_id',
            # Add more mappings as needed
        }
        df = df.rename(columns=column_mapping)

        return self.bulk_insert_features(df, table_name)

    def create_tables_if_not_exist(self, schema_path: Path):
        """Execute DDL from schema file"""
        logger.info(f"Executing DDL from {schema_path}")
        with open(schema_path, 'r') as f:
            ddl = f.read()

        with self.engine.begin() as conn:
            conn.execute(text(ddl))

        logger.info("Tables created successfully")

    def truncate_table(self, table_name: str):
        """Truncate table (dev/testing only)"""
        with self.engine.begin() as conn:
            conn.execute(text(f"TRUNCATE TABLE {table_name} RESTART IDENTITY CASCADE"))
        logger.warning(f"Truncated table: {table_name}")

    def get_row_count(self, table_name: str) -> int:
        """Get current row count"""
        with self.engine.connect() as conn:
            result = conn.execute(
                text(f"SELECT COUNT(*) FROM {table_name}")
            ).scalar()
        return result


# CLI usage
if __name__ == "__main__":
    import argparse
    import logging
    from pathlib import Path

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
    )

    parser = argparse.ArgumentParser(description="IMS ingestor CLI")
    parser.add_argument("--test", action="store_true", help="Test DB connection and exit")
    parser.add_argument(
        "--parquet",
        type=str,
        default=None,
        help="Path to parquet file to ingest (e.g. data/processed/set1_features.parquet)",
    )
    parser.add_argument(
        "--table",
        type=str,
        default="features",
        help="Target DB table name for ingestion (default: features)",
    )
    args = parser.parse_args()

    ingestor = IMSIngestor()

    # Quick DB test
    if args.test:
        ok = ingestor.test_connection()
        if not ok:
            print("DB connection failed")
            raise SystemExit(1)
        print("Database connection OK")
        raise SystemExit(0)

    # Ingest parquet if provided
    if args.parquet:
        parquet_path = Path(args.parquet)
        if not parquet_path.exists():
            print(f"Parquet file not found: {parquet_path}")
            raise SystemExit(2)
        n_rows = ingestor.ingest_from_parquet(parquet_path, table_name=args.table)
        print(f"\n✓ Ingested {n_rows} rows into {args.table}")
        count = ingestor.get_row_count(args.table)
        print(f"✓ Total rows in {args.table}: {count}")
        raise SystemExit(0)

    # If nothing provided, print help
    parser.print_help()
